local Permissions = require("weave.permissions")
local Session = require("weave.session")

describe("session permission isolation", function()
  before_each(function()
    Permissions._reset()
    Permissions.set_mode("on")
    Permissions.set_active("auto")
  end)
  after_each(function() Permissions._reset() end)

  it("copies defaults into independent engines, including sandbox grants", function()
    local a = Permissions.new()
    local b = Permissions.new()
    a.set_active("read_only")
    a.add_grant({ tool = "weave:write", decision = "allow" })
    a.add_bind_grant({ path = "/private-a", mode = "ro" })
    a.set_network_granted(true)
    a.set_tool_sandbox_disabled(true)
    assert.equal("auto", b.active().name)
    assert.equal(0, #b.grants())
    assert.equal(0, #b.bind_grants())
    assert.is_false(b.network_granted())
    assert.is_false(b.tool_sandbox_disabled())
    assert.equal("auto", Permissions.active().name)
  end)

  it("accepts a preset, first-match rule overrides and sandbox overrides without mutating templates", function()
    local a = Permissions.new({ preset = "read_only",
      rules = { { tool = "weave:read", decision = "deny" } },
      sandbox = { network = true, tools = { ["weave:task_start"] = { enabled = false } } },
    })
    assert.equal("deny", a.resolve({ tool = "weave:read", resource = "/src/main.lua" }))
    assert.is_true(a.tool_sandbox().network)
    assert.is_false(a.tool_sandbox(nil, "weave:task_start").enabled)
    assert.is_false(Permissions.get("read_only").sandbox.network == true)
    assert.equal("allow", Permissions.new({ preset = "read_only" }).resolve({
      tool = "weave:read", resource = Permissions.project_root() .. "/main.lua",
    }))
  end)

  it("snapshots inherited rules and grants without inheriting future mutations", function()
    local a = Permissions.new({ preset = "read_only" })
    a.add_grant({ tool = "weave:write", resource = "/approved/**", decision = "allow" })
    local b = Permissions.new(nil, a)
    a.clear_overlay()
    a.set_active("yolo")
    assert.equal("read_only", b.active().name)
    assert.equal("allow", b.resolve({ tool = "weave:write", resource = "/approved/x" }))
    assert.equal(1, #b.grants())
  end)

  it("shares the preset catalogue but snapshots each selected policy", function()
    local a, b = Permissions.new(), Permissions.new()
    Permissions.save_preset({ name = "shared-new", rules = { { tool = "*", decision = "allow" } } })
    a.set_active("shared-new")
    b.set_active("shared-new")
    Permissions.save_preset({ name = "shared-new", rules = { { tool = "*", decision = "deny" } } })
    assert.equal("allow", a.resolve({ tool = "example" }))
    b.set_active("shared-new")
    assert.equal("deny", b.resolve({ tool = "example" }))
    assert.equal("allow", a.resolve({ tool = "example" }))
  end)

  it("publishes saved definitions but applies an edit only to its originating session", function()
    local a, b = Permissions.new({ preset = "read_only" }), Permissions.new({ preset = "read_only" })
    a.save_preset({ name = "read_only", rules = { { tool = "*", decision = "deny" } },
      sandbox = { enabled = false } })
    assert.equal("runtime", Permissions.get("read_only").source)
    assert.equal("deny", a.resolve({ tool = "weave:read", resource = Permissions.project_root() .. "/x" }))
    assert.equal("allow", b.resolve({ tool = "weave:read", resource = Permissions.project_root() .. "/x" }))
    assert.is_true(b.tool_sandbox().enabled)
    assert.is_false(a.tool_sandbox().enabled)
  end)

  it("retains another session's selected policy after its template is deleted", function()
    Permissions.save_preset({ name = "temporary", rules = { { tool = "*", decision = "deny" } } })
    local a, b = Permissions.new({ preset = "temporary" }), Permissions.new({ preset = "temporary" })
    a.delete_preset("temporary")
    assert.is_nil(Permissions.get("temporary"))
    assert.is_true(a.active().name ~= "temporary")
    assert.equal("deny", b.resolve({ tool = "example" }))
    local child = Permissions.new(nil, b)
    assert.equal("temporary", child.active().name)
    assert.equal("deny", child.resolve({ tool = "example" }))
  end)

  it("notifies catalogue observers without replacing their active snapshots", function()
    local a, changes = Permissions.new(), 0
    local unsubscribe = a.subscribe(function() changes = changes + 1 end)
    Permissions.save_preset({ name = "later", rules = {} })
    assert.equal(1, changes)
    assert.is_not_nil(a.get("later"))
    assert.equal("auto", a.active().name)
    unsubscribe()
    Permissions.delete_preset("later")
    assert.equal(1, changes)
  end)

  it("inherits local policy overrides without publishing them to the catalogue", function()
    local a = Permissions.new({ rules = { { tool = "weave:read", decision = "deny" } },
      sandbox = { enabled = false } })
    local child = Permissions.new(nil, a)
    assert.equal("deny", child.resolve({ tool = "weave:read", resource = "/any" }))
    assert.is_false(child.tool_sandbox().enabled)
    assert.is_true(Permissions.new().tool_sandbox().enabled)
    assert.is_true(Permissions.get("auto").sandbox.enabled ~= false)
  end)

  it("reconciles inherited presets when the effective process mode differs", function()
    local base = Permissions.new({ preset = "ask" })
    base.current_mode = function() return "off" end
    assert.equal("unsandboxed_ask", Permissions.new(nil, base).active().name)
    assert.has_error(function() Permissions.new({ preset = "ask" }, base) end)
  end)

  it("exposes a session-owned engine and rejects invalid permission construction", function()
    local a = Session:new({ permissions = { preset = "read_only" } })
    local b = Session:new()
    assert.equal("read_only", a:permissions().active().name)
    assert.is_true(a:permissions() ~= b:permissions())
    assert.has_error(function() Permissions.new({ preset = "missing" }) end)
    assert.has_error(function() Permissions.new({ sandbox = { enabled = "no" } }) end)
  end)
end)
