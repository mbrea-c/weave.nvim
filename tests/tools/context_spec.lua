local Session = require("weave.session")
local Context = require("weave.tool_context")

describe("session transport capabilities", function()
  it("authenticates distinct sessions without trusting request arguments", function()
    local a, b = Session:new(), Session:new()
    a:_reset_config_session(true)
    b:_reset_config_session(true)
    local ta, tb = Context.bind(a), Context.bind(b)
    assert.equal(64, #ta)
    assert.is_true(ta ~= tb)
    assert.rawequal(a, Context.authenticate(ta).session)
    assert.rawequal(b, Context.authenticate(tb).session)
    assert.is_nil(Context.authenticate("forged"))
    assert.is_nil(Context.authenticate(nil))
  end)

  it("revokes connections and pending call contexts across reset and stop", function()
    local s = Session:new()
    s:_reset_config_session(true)
    local token = Context.bind(s)
    local caller = Context.authenticate(token)
    assert.is_true(caller.valid())
    s:_reset_config_session(true)
    assert.is_false(caller.valid())
    assert.is_nil(Context.authenticate(token))
    local fresh = Context.bind(s)
    assert.is_true(fresh ~= token)
    s:stop()
    assert.is_nil(Context.authenticate(fresh))
  end)
end)
